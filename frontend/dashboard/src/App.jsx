import { useEffect, useState } from 'react';
import fixtureReport from './data/replay-report.json';

const fmt$ = (n) =>
  n == null ? '-' : `$${Number(n).toFixed(4)}`;
const fmtPct = (n) =>
  n == null ? '-' : `${(Number(n) * 100).toFixed(1)}%`;

function Banner({ mode, live }) {
  if (mode === 'live' && live) {
    return (
      <div className="banner live">
        <strong>LIVE PAPER DATA</strong>
        <span>
          {live.n_scans} live venue scans ({live.scan_range[0].slice(0, 16).replace('T', ' ')}
          {' → '}
          {live.scan_range[1].slice(0, 16).replace('T', ' ')}) rendered from the
          paper-trading ledger. Paper trading only: no real money, no live orders.
        </span>
      </div>
    );
  }
  return (
    <div className="banner">
      <strong>SIMULATED FIXTURE DATA</strong>
      <span>
        This dashboard renders a replay report generated by the paper
        execution engine over labeled simulated snapshots. Paper trading
        only: no real money, no live orders.
      </span>
    </div>
  );
}

function ModeToggle({ mode, setMode, liveAvailable }) {
  return (
    <div className="mode-toggle">
      <button
        className={mode === 'fixture' ? 'active' : ''}
        onClick={() => setMode('fixture')}
      >
        Simulated fixture
      </button>
      <button
        className={mode === 'live' ? 'active' : ''}
        onClick={() => setMode('live')}
        disabled={!liveAvailable}
        title={liveAvailable ? 'Live paper scans' : 'No live scans yet: run scripts/scan_live.py, then scripts/export_live_report.py'}
      >
        Live paper scans
      </button>
    </div>
  );
}

function SummaryCards({ r }) {
  const cards = [
    { label: 'Snapshots replayed', value: r.n_snapshots },
    { label: 'Opportunities detected', value: r.n_opportunities },
    { label: 'Executed (paper)', value: r.n_executed },
    { label: 'Rejected by risk', value: r.n_rejected },
    { label: 'Expected net P&L', value: fmt$(r.total_expected_net), money: true },
    { label: 'Realized net P&L', value: fmt$(r.total_realized_net), money: true },
    {
      label: 'Hit rate',
      value: fmtPct(r.hit_rate),
      note: r.n_executed < 30 ? 'n too small: not significant' : null,
    },
  ];
  return (
    <div className="cards">
      {cards.map((c) => (
        <div className="card" key={c.label}>
          <div className="card-label">{c.label}</div>
          <div className={'card-value' + (c.money ? ' money' : '')}>{c.value}</div>
          {c.note && <div className="card-note">{c.note}</div>}
        </div>
      ))}
    </div>
  );
}

function Flags({ flags }) {
  if (!flags || flags.length === 0) return null;
  return (
    <section className="panel">
      <h2>Honesty flags</h2>
      <ul className="flags">
        {flags.map((f) => (
          <li key={f}>{f}</li>
        ))}
      </ul>
    </section>
  );
}

function OpportunityRow({ row }) {
  const [open, setOpen] = useState(false);
  return (
    <>
      <tr onClick={() => setOpen(!open)} className={open ? 'open' : ''}>
        <td className="mono">{row.opportunity_id.slice(0, 28)}…</td>
        <td>{row.strategy}</td>
        <td className="mono">{row.detected_at.slice(0, 19).replace('T', ' ')}</td>
        <td className="num">{row.sized_quantity.toFixed(1)}</td>
        <td>
          <span className={`pill ${row.decision === 'PAPER_EXECUTE' ? 'go' : 'stop'}`}>
            {row.decision}
          </span>
        </td>
        <td className="num">{fmt$(row.expected_net)}</td>
        <td className="num">{row.realized_net == null ? '—' : fmt$(row.realized_net)}</td>
        <td>{row.trade_statuses.join(', ') || '—'}</td>
      </tr>
      {open && (
        <tr className="detail">
          <td colSpan={8}>
            <OpportunityDetail row={row} />
          </td>
        </tr>
      )}
    </>
  );
}

function OpportunityDetail({ row }) {
  // The fixture rows are flattened; full explanation lives in the report
  // JSON under rows[]. We render what the engine recorded.
  return (
    <div className="detail-body">
      <div className="detail-grid">
        <div>
          <h4>Outcome</h4>
          <p>
            Expected {fmt$(row.expected_net)} → realized{' '}
            {row.realized_net == null ? '—' : fmt$(row.realized_net)}
          </p>
        </div>
        <div>
          <h4>Label</h4>
          <p className="mono">{row.label}</p>
        </div>
        <div>
          <h4>Trade statuses</h4>
          <p>{row.trade_statuses.join(', ') || '—'}</p>
        </div>
        <div>
          <h4>Notes</h4>
          <ul>
            {(row.notes || []).map((n) => (
              <li key={n}>{n}</li>
            ))}
          </ul>
        </div>
      </div>
      <p className="hint">
        Full cost waterfall (raw edge → fees → slippage → latency → net) and
        the human-readable explanation are stored on the opportunity record
        in the engine; this fixture carries the replay-level summary.
      </p>
    </div>
  );
}

function OpportunitiesTable({ rows }) {
  if (!rows || rows.length === 0) {
    return (
      <section className="panel">
        <h2>Opportunities</h2>
        <p className="empty">No opportunities detected in this replay.</p>
      </section>
    );
  }
  return (
    <section className="panel">
      <h2>Opportunities ({rows.length})</h2>
      <p className="hint">Click a row to expand.</p>
      <div className="table-wrap">
        <table>
          <thead>
            <tr>
              <th>ID</th>
              <th>Strategy</th>
              <th>Detected</th>
              <th>Qty</th>
              <th>Decision</th>
              <th>Expected</th>
              <th>Realized</th>
              <th>Fills</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <OpportunityRow key={r.opportunity_id} row={r} />
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}

function Attribution({ attr }) {
  if (!attr || Object.keys(attr).length === 0) return null;
  const rows = [
    ['Gross expected edge', attr.gross_expected_edge],
    ['Trading fees', attr.trading_fees],
    ['Slippage (VWAP vs touch)', attr.slippage],
    ['Latency adjustment', attr.latency_adjustment],
    ['Net expected', attr.net_expected],
    ['Realized net', attr.realized_net],
    ['Realized minus expected', attr.realized_minus_expected],
  ];
  return (
    <section className="panel">
      <h2>P&amp;L attribution</h2>
      <p className="hint">
        Expected gross edge decomposed into modeled costs, versus realized.
        The gap includes $1 settlement payouts on paired fills and partial-fill effects.
      </p>
      <table>
        <tbody>
          {rows.map(([label, v]) => (
            <tr key={label}>
              <td>{label}</td>
              <td className="num">{fmt$(v)}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </section>
  );
}

export default function App() {
  const [mode, setMode] = useState('fixture');
  const [live, setLive] = useState(null);
  useEffect(() => {
    fetch('live-report.json')
      .then((r) => (r.ok ? r.json() : null))
      .then((j) => {
        if (j) setLive(j);
      })
      .catch(() => {});
  }, []);
  const r = mode === 'live' && live ? live : fixtureReport;
  return (
    <div className="app">
      <header>
        <div>
          <h1>ODDS — Paper Trading Replay</h1>
          <p className="subtitle">
            Prediction-market mispricing engine · detect → size → risk-gate →
            paper-execute · chronological, no look-ahead
          </p>
        </div>
        <div className="config">
          <span>Kelly ×{r.config_notes.kelly_fraction}</span>
          <span>Bankroll ${r.config_notes.bankroll}</span>
          <span>Labels: {r.labels.join(', ')}</span>
        </div>
      </header>
      <ModeToggle mode={mode} setMode={setMode} liveAvailable={!!live} />
      <Banner mode={mode} live={live} />
      <SummaryCards r={r} />
      <Attribution attr={r.attribution} />
      <Flags flags={r.flags} />
      <OpportunitiesTable rows={r.rows} />
      <footer>
        Engine: Python (fees, detection, Kelly sizing, risk gates, paper
        broker, replay). No real orders are ever placed.{' '}
        {mode === 'live'
          ? 'Figures above are paper-trading results on live quotes and carry no statistical significance at this sample size.'
          : 'Figures above are simulated and carry no statistical significance at this sample size.'}
      </footer>
    </div>
  );
}
